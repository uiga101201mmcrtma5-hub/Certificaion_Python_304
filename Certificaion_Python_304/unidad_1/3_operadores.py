#OPERADORES RELACIONALES
a=10
b=5
#MENOR QUE(<)
resultado=a<b
print(resultado)
#MAYOR QUE(>)
resultado=a>b
print(resultado)
#DIFERENTE QUE(!=)
resultado=a!=b
print(resultado)
#IGUAL QUE(==)
resultado=a==b
print(resultado)
#MENOR O IGUAL QUE(<=)
resultado=a<=b
print(resultado)
#MENOR O IGUAL QUE(>=)
resultado=a>=b
print(resultado)
#OPERADORES LOGICOS
#AND(Y)
x=15
z=9
resultado=(x>a)and(z!=b)
print(resultado)
resultado=(x==a)or(z<=b)
print(resultado)
resultado=not((x==a)or(z<=b))
print(resultado)
